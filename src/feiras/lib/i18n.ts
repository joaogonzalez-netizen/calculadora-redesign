type Vars = Record<string, string | number>;

function formatar(texto: string, vars?: Vars): string {
  if (!vars) return texto;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Dicionários { pt, en } derivados da tabela. */
export const DICIONARIOS: { pt: Record<string, string>; en: Record<string, string> } = { pt: {}, en: {} };
for (const [k, [pt, en]] of Object.entries(D)) { DICIONARIOS.pt[k] = pt; DICIONARIOS.en[k] = en; }

/** Tradução fora de componentes (libs, store). Usa o idioma do formato, mantido pelo provider. */
export function traduzirFeiras(idioma: Idioma, chave: string, vars?: Vars): string {
  const dic = idioma === 'en' ? DICIONARIOS.en : DICIONARIOS.pt;
  return formatar(dic[chave] ?? DICIONARIOS.pt[chave] ?? chave, vars);
}
export const tf = (chave: string, vars?: Vars) => traduzirFeiras(idiomaDoFormato(), chave, vars);

export function useFeirasT() {
  const { idioma } = useI18n();
  const t = useCallback((chave: string, vars?: Vars) => traduzirFeiras(idioma, chave, vars), [idioma]);
  return { t, idioma };
}

